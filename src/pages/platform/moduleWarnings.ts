// 截图中的汇总是该平台全部任务的统计，下方表格展示预警关联任务。
export function getWarningSummary(key: string) {
  const expanded = ['rule', 'risk', 'process', 'quality', 'credit', 'service'].includes(key)
  return {
    dispatches: expanded ? '45' : '88',
    taskCounts: expanded ? [16, 2, 14] : [5, 2, 3],
    visibleTasks: ['rule', 'risk', 'quality'].includes(key) ? 3 : 2,
  }
}


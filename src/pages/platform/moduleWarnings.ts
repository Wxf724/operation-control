export function getModuleWarnings(moduleKey: string) {
  const metrics = MODULE_METRICS[moduleKey] ?? []
  return MODULE_WARNINGS[moduleKey]?.map(warning => ({
    ...warning,
    description: warning.description.replace(/\{(\w+)\}/g, (_, key: string) => {
      const metric = metrics.find(item => item.key === key)
      return metric ? `${metric.value}${metric.unit ?? ''}` : '暂无数据'
    }),
  }))
}

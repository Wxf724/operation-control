/** 千分位金额 */
function formatAmount(value: number): string {
  if (!value) return '0'
  return value.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

/** 取第 start 条起的 count 条单据：前 12 条照参考图，其余按行号生成 */
export function getRectifyDocRows(start: number, count: number): readonly string[][] {
  const rows: string[][] = []

  for (let i = 0; i < count; i += 1) {
    const n = start + i

    if (n < RECTIFY_DOC_SEED_ROWS.length) {
      rows.push([...RECTIFY_DOC_SEED_ROWS[n]])
      continue
    }

    const org = RECTIFY_DOC_ORGS[n % RECTIFY_DOC_ORGS.length]
    const maker = RECTIFY_DOC_MAKERS[(n * 3) % RECTIFY_DOC_MAKERS.length]
    const biz = RECTIFY_DOC_BIZ[(n * 5) % RECTIFY_DOC_BIZ.length]
    const dept = RECTIFY_DOC_DEPTS[(n * 7) % RECTIFY_DOC_DEPTS.length]
    const digest = RECTIFY_DOC_DIGESTS[(n * 11) % RECTIFY_DOC_DIGESTS.length]
    const amount = (n * 7919) % 9000000

    rows.push([
      org[0],
      org[1],
      `BX${String(20250000000 + n * 37)}`,
      maker[0],
      maker[1],
      biz[0],
      biz[1],
      dept[0],
      dept[1],
      formatAmount(amount / 100),
      digest,
    ])
  }

  return rows
}

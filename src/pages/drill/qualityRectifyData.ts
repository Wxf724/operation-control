/** 按页签取行：前置维度值 + 共用的数值列 */
export function getRectifyRows(tab: string): readonly string[][] {
  return RECTIFY_VALUES.map((values, i) => {
    switch (tab) {
      case 'region':
        return [RECTIFY_REGIONS[i], ...values]
      case 'person':
        return [...RECTIFY_PERSONS[i], ...values]
      case 'group':
        return [...RECTIFY_GROUPS[i], ...values]
      default:
        return [...RECTIFY_UNITS[i], ...values]
    }
  })
}


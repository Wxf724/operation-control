const RPA_CONTRIB_BILL_ACTIONS: readonly string[] = ['报销单', '借款单', '付款单']

/** 去年同期固定 0.5 分钟，同比按本期值现算（保留两位小数，与参考图口径一致） */
function buildRows(): readonly string[][] {
  const rows: string[][] = RPA_CONTRIB_SEED_ROWS.map((row) => [...row])
  let n = 0

  for (const kind of RPA_CONTRIB_FEE_KINDS) {
    for (const action of RPA_CONTRIB_BILL_ACTIONS) {
      const duration = Number((0.12 + ((n * 17) % 90) / 100).toFixed(2))
      const yoy = (((duration - 0.5) / 0.5) * 100).toFixed(2)
      const code = `20000000${String(180 + n).padStart(4, '0')}`
      rows.push([code, `${kind}${action}`, String(duration), '0.5', `${yoy}%`])
      n += 1
    }
  }

  return rows
}

/** 明细表 141 行：业务类型编码 / 业务类型名称 / 平均处理时长 / 去年同期 / 同比 */
export const RPA_CONTRIB_ROWS: readonly string[][] = buildRows()
